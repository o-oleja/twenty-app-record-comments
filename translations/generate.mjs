// Writes locales/<locale>.json and src/utils/strings.generated.ts from translations.mjs.
// Run `twenty app translations extract` first if entity labels changed, then `yarn translations`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { LOCALES } from './translations.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = LOCALES.en;
const placeholders = (text) => [...text.matchAll(/\{(\w+)\}/g)].map(([, name]) => name).sort().join(',');

// 1. Every locale has every key, with the same placeholders as English.
const problems = [];
for (const [locale, { ui, meta }] of Object.entries(LOCALES)) {
  for (const [group, reference, strings] of [
    ['ui', source.ui, ui],
    ['meta', source.meta, meta],
  ]) {
    for (const key of Object.keys(reference)) {
      const value = strings?.[key];
      if (typeof value !== 'string' || value.trim() === '') {
        problems.push(`${locale}: missing ${group}.${key}`);
      } else if (placeholders(value) !== placeholders(reference[key])) {
        problems.push(`${locale}: placeholders differ in ${group}.${key}`);
      }
    }
    for (const key of Object.keys(strings ?? {})) {
      if (!(key in reference)) problems.push(`${locale}: unknown ${group}.${key}`);
    }
  }
}

// 2. Metadata catalogs: the CLI keys them by the English source string.
const catalogTemplate = JSON.parse(readFileSync(join(root, 'locales/en.json'), 'utf8'));
const metaKeyBySource = new Map(Object.entries(source.meta).map(([key, text]) => [text, key]));
for (const section of Object.values(catalogTemplate)) {
  for (const text of Object.keys(section)) {
    if (!metaKeyBySource.has(text)) problems.push(`locales/en.json: no meta entry for "${text}"`);
  }
}

if (problems.length > 0) {
  console.error(problems.join('\n'));
  process.exit(1);
}

for (const [locale, { meta }] of Object.entries(LOCALES)) {
  if (locale === 'en') continue;
  const catalog = Object.fromEntries(
    Object.entries(catalogTemplate).map(([sectionName, section]) => [
      sectionName,
      Object.fromEntries(Object.keys(section).map((text) => [text, meta[metaKeyBySource.get(text)]])),
    ]),
  );
  writeFileSync(join(root, `locales/${locale}.json`), `${JSON.stringify(catalog, null, 2)}\n`);
}

// 3. UI strings for the front component.
const uiStrings = Object.fromEntries(Object.entries(LOCALES).map(([locale, { ui }]) => [locale, ui]));
writeFileSync(
  join(root, 'src/utils/strings.generated.ts'),
  `// Generated by translations/generate.mjs from translations/translations.mjs. Do not edit.\n` +
    `export const UI_STRINGS = ${JSON.stringify(uiStrings, null, 2)} as const;\n`,
);

console.log(`Wrote ${Object.keys(LOCALES).length - 1} metadata catalogs and UI strings for ${Object.keys(LOCALES).length} locales.`);
